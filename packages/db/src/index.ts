// Keep Prisma's public type/value surface on the legacy client so the existing
// application services continue to share one set of generated input types.
// Explicit raw-query fragments must use RuntimePrisma because the runtime
// client is the D5-generated client.
// The application still imports Prisma's legacy namespace for generated input
// and JSON types. Point the runtime error constructor at the client that is
// actually executing queries so existing conflict classifiers keep working.
Object.defineProperty(LegacyPrisma, "PrismaClientKnownRequestError", {
  configurable: true,
  value: RuntimePrisma.PrismaClientKnownRequestError
});
export { LegacyPrisma as Prisma };
export { RuntimePrisma };

